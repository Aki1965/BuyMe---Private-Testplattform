export const CATEGORIES=CATEGORY_TREE.map(g=>g.name);
export function categoryInfo(value){return CATEGORY_TREE.find(g=>g.name===value||g.id===value||g.aliases.includes(value));}
export function categoryName(value){return categoryInfo(value)?.name||value||'';}
export function sameCategory(a,b){return categoryName(a)===categoryName(b);}
export function subcategoriesFor(value){return categoryInfo(value)?.subcategories||[];}
export function classificationLabel(item){const parent=categoryName(item.category);return item.subcategory?parent+' › '+item.subcategory:parent;}
export function validateClassification(category,subcategory=''){
 const group=categoryInfo(category);if(!group)throw Error('Bitte eine gültige Hauptkategorie auswählen.');
 const child=String(subcategory||'').trim();
 if(group.subcategories.length&&!child)throw Error('Bitte eine Unterkategorie auswählen.');
 if(child&&!group.subcategories.includes(child))throw Error('Diese Unterkategorie gehört nicht zur gewählten Hauptkategorie.');
 return {category:group.name,subcategory:child};
}
