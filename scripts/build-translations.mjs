import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const directory=path.join(root,'translations'),files=fs.readdirSync(directory).filter(n=>n.endsWith('.tsv')).sort(),dictionary={};
for(const name of files){
  for(const [i,line] of fs.readFileSync(path.join(directory,name),'utf8').split('\n').entries()){
    if(!line.trim()||line.startsWith('#'))continue;
    const row=line.split('|');
    if(row.length!==6||row.some(v=>!v.trim()))throw Error(`${name}:${i+1}: Deutsch und fünf vollständige Übersetzungen erwartet.`);
    if(Object.hasOwn(dictionary,row[0]))throw Error('Doppelter Schlüssel: '+row[0]);
    dictionary[row[0]]=row.slice(1);
  }
}
const target=path.join(root,'js/i18n-data.js');
const content='// Generated by scripts/build-translations.mjs from the reviewed local catalogs.\nexport const DICTIONARY='+JSON.stringify(dictionary,null,1)+';\n';
if(process.argv.includes('--check')){
  if(fs.readFileSync(target,'utf8')!==content)throw Error('Übersetzungsdatei ist veraltet. Bitte npm run translations:build ausführen.');
  console.log('Übersetzungen konsistent: '+Object.keys(dictionary).length+' deutsche Texte, fünf Zielsprachen.');
}else{fs.writeFileSync(target,content);console.log(Object.keys(dictionary).length+' Texte für sechs Sprachen erzeugt.');}
